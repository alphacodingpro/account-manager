import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { build } from "esbuild";
const out = join(mkdtempSync(join(tmpdir(), "rt-")), "rt.mjs");
await build({ entryPoints: ["apps/web/src/lib/reportTotals.ts"], bundle: true, format: "esm", platform: "node", outfile: out, logLevel: "error" });
const { addReportTotals } = await import(out);
const tb = addReportTotals("Trial Balance", [{ account_code: "1000", account_name: "Cash", debit: 100.1, credit: 0 }, { account_code: "3000", account_name: "Equity", debit: 0, credit: 100.1 }]);
assert.equal(tb.at(-1).account_name, "Total"); assert.equal(tb.at(-1).debit, 100.1); assert.equal(tb.at(-1).credit, 100.1);
const pl = addReportTotals("Profit & Loss", [{ category: "income", amount: 1000 }, { category: "expense", amount: 400 }]);
assert.deepEqual(pl.slice(-3).map((r) => [r.account_name, r.amount]), [["Total income", 1000], ["Total expenses", 400], ["Net profit", 600]]);
const loss = addReportTotals("Profit & Loss", [{ category: "income", amount: 100 }, { category: "expense", amount: 400 }]);
assert.equal(loss.at(-1).account_name, "Net loss"); assert.equal(loss.at(-1).amount, -300);
const bs = addReportTotals("Balance Sheet", [{ category: "asset", amount: 700 }, { category: "liability", amount: 200 }, { category: "equity", amount: 500 }]);
assert.equal(bs.find((r) => r.account_name === "Total assets").amount, 700);
assert.equal(bs.find((r) => r.account_name === "Total liabilities and equity").amount, 700);
const gst = addReportTotals("GST Summary", [{ period: "2026-09", sales_value: 100, output_gst: 18, purchase_value: 50, input_gst: 9, net_gst_payable: 9 }, { period: "2026-10", sales_value: 200, output_gst: 36, purchase_value: 0, input_gst: 0, net_gst_payable: 36 }]);
assert.deepEqual([gst.at(-1).period, gst.at(-1).output_gst, gst.at(-1).input_gst, gst.at(-1).net_gst_payable], ["Total", 54, 9, 45]);
assert.deepEqual(addReportTotals("Cash Flow", [{ a: 1 }]), [{ a: 1 }]);
assert.deepEqual(addReportTotals("Trial Balance", []), []);
console.log("Report totals checks passed.");
